package resources

import (
	corev1 "k8s.io/api/core/v1"

	hermesv1 "github.com/paperclipinc/hermes-operator/api/v1"
)

const (
	// ConfigSeedContainerName is the init container that copies the rendered
	// config.yaml onto the data volume and runs the agent's config schema
	// migration. The controller looks for it by name to surface a failed
	// migration as Ready=False/ConfigMigrationFailed.
	ConfigSeedContainerName = "config-seed"

	// ConfigStagingMountPath is where the instance ConfigMap is mounted read
	// only inside the config-seed init container.
	ConfigStagingMountPath = "/etc/hermes-operator/config"

	// agentHome is HERMES_HOME on the upstream image (the data volume).
	agentHome = "/opt/data"

	// skipConfigMigrationEnv is the upstream escape hatch honored by
	// scripts/docker_config_migrate.py. It is forwarded from spec.env to the
	// config-seed container so a user can still opt out of boot-time migration.
	skipConfigMigrationEnv = "HERMES_SKIP_CONFIG_MIGRATION"
)

// configSeedScript copies the declared config onto the writable data volume and
// then runs the same migration the image's s6 stage2 hook runs, but fails the
// init container instead of logging a warning and continuing.
//
// Why: the agent migrates config.yaml in place when the image moves to a newer
// config schema. When config.yaml was a read-only ConfigMap subPath mount the
// rewrite failed with EROFS, stage2 printed one warning, and the gateway came up
// Ready on a config that silently meant something else (renamed keys fall back
// to defaults). See #160.
//
// The copy overwrites on every pod start, so the ConfigMap stays authoritative;
// the agent's own additions (_config_version, recomputed toolset lists) are
// regenerated by the migration that follows. The write is atomic (tmp + mv) so
// a crash mid copy never leaves a truncated config behind.
//
// Images that predate scripts/docker_config_migrate.py skip the migration step;
// the copy alone already makes config.yaml writable for them.
const configSeedScript = `set -eu
home="${HERMES_HOME:-/opt/data}"
src="` + ConfigStagingMountPath + `/config.yaml"
dest="$home/config.yaml"
owner="${HERMES_UID:-1000}:${HERMES_GID:-1000}"

cp "$src" "$dest.operator-tmp"
mv -f "$dest.operator-tmp" "$dest"
chown "$owner" "$dest" 2>/dev/null || true
echo "[config-seed] wrote $dest from the instance ConfigMap"

py=/opt/hermes/.venv/bin/python
migrate=/opt/hermes/scripts/docker_config_migrate.py
if [ ! -x "$py" ] || [ ! -f "$migrate" ]; then
  echo "[config-seed] image has no $migrate; skipping init time config migration"
  exit 0
fi

rc=0
(cd /opt/hermes && "$py" "$migrate") || rc=$?

# The migration ran as root here; hand everything it may have written back to
# the agent user so the dropped privilege gateway can keep writing it.
for p in "$dest" "$home/.env" "$home/backups"; do
  [ -e "$p" ] && chown -R "$owner" "$p" 2>/dev/null || true
done

if [ "$rc" -ne 0 ]; then
  echo "config schema migration failed (exit $rc); refusing to start the agent on an unmigrated config. Fix spec.config or set HERMES_SKIP_CONFIG_MIGRATION=1 in spec.env to start anyway." >&2
  exit "$rc"
fi
echo "[config-seed] config schema is current"
`

// BuildConfigSeedContainer returns the init container that makes config.yaml
// writable for the agent (see configSeedScript). It reuses the agent image, so
// no extra image is pulled and the migration code always matches the agent
// that will read the result.
func BuildConfigSeedContainer(inst *hermesv1.HermesInstance, securityCtx *corev1.SecurityContext) corev1.Container {
	env := []corev1.EnvVar{
		{Name: "HERMES_HOME", Value: agentHome},
		{Name: "HERMES_UID", Value: "1000"},
		{Name: "HERMES_GID", Value: "1000"},
	}
	for _, e := range inst.Spec.Env {
		if e.Name == skipConfigMigrationEnv {
			env = append(env, e)
		}
	}
	return corev1.Container{
		Name:            ConfigSeedContainerName,
		Image:           imageRef(inst),
		ImagePullPolicy: pullPolicy(inst),
		// Command overrides the image ENTRYPOINT (s6 /init), which must not run
		// here: it insists on being PID 1 and would start the gateway.
		Command: []string{"/bin/sh", "-c", configSeedScript},
		Env:     env,
		// FallbackToLogsOnError puts the migration error (the tail of the log)
		// into the terminated state message, which the controller copies into
		// the Ready condition.
		TerminationMessagePath:   "/dev/termination-log",
		TerminationMessagePolicy: corev1.TerminationMessageFallbackToLogsOnError,
		SecurityContext:          securityCtx,
		// Same requests/limits as the agent: init containers do not add to the
		// pod's effective request beyond the max, and namespaces with a
		// ResourceQuota require every container to declare them.
		Resources: agentResources(inst),
		VolumeMounts: []corev1.VolumeMount{
			{Name: "data", MountPath: agentHome},
			{Name: "config", MountPath: ConfigStagingMountPath, ReadOnly: true},
			{Name: "tmp", MountPath: "/tmp"},
		},
	}
}
